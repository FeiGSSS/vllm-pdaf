"""Generate a deterministic Markdown index from the PAP experiment registry."""

from __future__ import annotations

import argparse
from pathlib import Path

from benchmarks.pap.validate_registry import (
    EXPERIMENT_DIR,
    PROFILE_DIR,
    RUN_DIR,
    RegistrySnapshot,
    validate_registry,
)


BEGIN_MARKER = "<!-- PAP-EXPERIMENT-INDEX:BEGIN -->"
END_MARKER = "<!-- PAP-EXPERIMENT-INDEX:END -->"


def _cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def render_generated_region(snapshot: RegistrySnapshot) -> str:
    """Render the generated experiment table.

    Args:
        snapshot: A validated registry snapshot.

    Returns:
        Markdown bounded by stable generated-region markers.
    """
    lines = [
        BEGIN_MARKER,
        "<!-- Generated by benchmarks/pap/generate_experiment_index.py. -->",
        "",
        (
            "| Experiment | Evidence | Decision | Validity | Runs | "
            "Successor | Conclusion |"
        ),
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    ordered = sorted(
        snapshot.experiments.values(),
        key=lambda item: (item["recorded_at"], item["experiment_id"]),
    )
    for experiment in ordered:
        successor = experiment["superseded_by"]
        successor_cell = "—" if successor is None else successor
        lines.append(
            "| "
            + " | ".join(
                _cell(value)
                for value in (
                    experiment["experiment_id"],
                    experiment["evidence"],
                    experiment["decision"],
                    experiment["validity"]["status"],
                    ", ".join(experiment["run_ids"]),
                    successor_cell,
                    experiment["conclusion"],
                )
            )
            + " |"
        )
    lines.extend(["", END_MARKER])
    return "\n".join(lines)


def update_generated_region(existing: str, generated: str) -> str:
    """Replace one generated region while preserving manual text.

    Args:
        existing: Existing Markdown content, possibly without markers.
        generated: Complete generated region including both markers.

    Returns:
        Updated Markdown content with one generated region.

    Raises:
        ValueError: If only one marker exists or marker ordering is invalid.
    """
    begin = existing.find(BEGIN_MARKER)
    end = existing.find(END_MARKER)
    if begin == end == -1:
        prefix = existing.rstrip()
        return f"{prefix}\n\n{generated}\n" if prefix else f"{generated}\n"
    if begin == -1 or end == -1 or end < begin:
        raise ValueError("invalid PAP experiment index markers")
    end += len(END_MARKER)
    return existing[:begin] + generated + existing[end:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile-dir", type=Path, default=PROFILE_DIR)
    parser.add_argument("--run-dir", type=Path, default=RUN_DIR)
    parser.add_argument("--experiment-dir", type=Path, default=EXPERIMENT_DIR)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    snapshot = validate_registry(
        profile_dir=args.profile_dir,
        run_dir=args.run_dir,
        experiment_dir=args.experiment_dir,
    )
    generated = render_generated_region(snapshot)
    if args.output is None:
        print(generated)
        return 0

    existing = (
        args.output.read_text(encoding="utf-8")
        if args.output.exists()
        else "# PAP experiment registry\n"
    )
    updated = update_generated_region(existing, generated)
    if args.check:
        if existing != updated:
            raise SystemExit(f"generated PAP index is stale: {args.output}")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(updated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
